import asyncio
import logging

from aiogram import Bot, Dispatcher
from aiogram.client.default import DefaultBotProperties
from aiogram.client.session.aiohttp import AiohttpSession

from bot import handlers
from bot.middlewares.get_user import GetUserMiddleware
from bot.middlewares.logging_query import UserLoggerMiddleware
from bot.middlewares.shadow_ban import ShadowBanMiddleware
from bot.scheduler import setup_scheduler
from config import config, scheduler
from DB import init_database
from utils.db_manager import backup_db

logger = logging.getLogger(__name__)


def _create_bot():
    session_kwargs = {}
    if config.tg_bot.proxy_url:
        logger.info('Proxy configured: %s', config.tg_bot.proxy_url)
        session_kwargs['proxy'] = config.tg_bot.proxy_url
    else:
        logger.info('No proxy configured, using direct connection')

    bot_name = config.tg_bot.bot_name
    metrics_port = config.tg_bot.metrics_port
    if bot_name and metrics_port:
        from aiogram_metrics import InstrumentedAiohttpSession, MetricsMiddleware, start_metrics_server

        start_metrics_server(port=metrics_port)
        logger.info('Metrics server started on :%s (bot=%s)', metrics_port, bot_name)
        session = InstrumentedAiohttpSession(bot_name=bot_name, **session_kwargs)
        metrics_middleware = MetricsMiddleware(bot_name=bot_name)
    else:
        session = AiohttpSession(**session_kwargs) if session_kwargs else None
        metrics_middleware = None
        logger.info('Metrics disabled (set BOT_NAME and METRICS_PORT to enable)')

    bot = Bot(
        token=config.tg_bot.token,
        default=DefaultBotProperties(parse_mode='HTML'),
        session=session,
    )
    return bot, metrics_middleware


async def _verify_proxy(bot: Bot) -> None:
    if not config.tg_bot.proxy_url:
        return
    try:
        me = await asyncio.wait_for(bot.get_me(), timeout=15)
        logger.info('Proxy connection verified — bot @%s is reachable', me.username)
    except asyncio.TimeoutError:
        logger.error('Proxy connection timed out (%s)', config.tg_bot.proxy_url)
        raise SystemExit(1)
    except Exception as exc:
        logger.error('Proxy connection failed (%s): %s', config.tg_bot.proxy_url, exc)
        raise SystemExit(1)


async def main() -> None:
    logger.info('Creating db tables')
    init_database()

    bot, metrics_middleware = _create_bot()
    await _verify_proxy(bot)

    dp = Dispatcher()
    if metrics_middleware:
        dp.update.outer_middleware(metrics_middleware)

    logger.info('Including routers')
    dp.include_router(handlers.admin.router)
    dp.include_router(handlers.master.router)
    dp.include_router(handlers.commands.router)
    dp.include_router(handlers.default.router)
    dp.include_router(handlers.callbacks.admin.router)
    dp.include_router(handlers.callbacks.master.router)
    dp.include_router(handlers.callbacks.appointment_pages.router)
    dp.include_router(handlers.callbacks.user_navigation.router)

    logger.info('Including middlewares')
    dp.update.middleware(GetUserMiddleware())
    dp.update.middleware(ShadowBanMiddleware())
    dp.message.middleware.register(UserLoggerMiddleware())
    dp.inline_query.middleware.register(UserLoggerMiddleware())

    me = await bot.get_me()
    logger.info('%s starting\n * Running on http://t.me/%s', me.first_name, me.username)

    await setup_scheduler(scheduler, bot)
    scheduler.add_job(backup_db, 'cron', hour=5, minute=0, args=(bot,))
    if metrics_middleware:
        from bot.metrics import refresh_business_gauges

        refresh_business_gauges()
        scheduler.add_job(refresh_business_gauges, 'interval', seconds=60, id='metrics_gauge_refresh')
    scheduler.start()
    try:
        await dp.start_polling(bot)
    except Exception as e:
        logger.exception(e)


if __name__ == '__main__':
    asyncio.run(main())
